// Package sqlc holds sqlc-generated database queries plus their
// hand-written companions in fts.go and recipe_list.go.
package sqlc

import "context"

// GetRecipeRowID, DeleteFTS and InsertFTS are hand-written companions to the
// generated queries in this package.
//
// sqlc's SQLite engine only resolves the implicit "rowid" pseudo-column
// through the FTS5 table-valued function call form
// ("SELECT rowid FROM recipes_fts(?)"). It rejects "rowid" as a plain
// column reference anywhere else - in a SELECT list, an INSERT
// column list, or a WHERE equality - on both real and virtual tables, so
// the three statements below cannot be generated by `sqlc generate` and are
// written directly against the same sqlc.DBTX abstraction instead. Their
// SQL is otherwise exactly what sqlc would have produced.

const getRecipeRowID = `-- name: GetRecipeRowID :one
SELECT rowid FROM recipes WHERE id = ?
`

// GetRecipeRowID returns the internal SQLite rowid of the recipe with id,
// used to key its entry in the contentless recipes_fts index.
func (q *Queries) GetRecipeRowID(ctx context.Context, id string) (int64, error) {
	row := q.db.QueryRowContext(ctx, getRecipeRowID, id)
	var rowid int64
	err := row.Scan(&rowid)
	return rowid, err
}

// The two full-text indexes, recipes_fts (whole words) and recipes_trigram
// (parts of words), hold the same four columns for the same rowid;
// DeleteFTS and InsertFTS always write both, so they cannot disagree.
var ftsTables = [...]string{"recipes_fts", "recipes_trigram"}

// DeleteFTS removes the full-text entries for the given rowid.
func (q *Queries) DeleteFTS(ctx context.Context, rowid int64) error {
	for _, table := range ftsTables {
		if _, err := q.db.ExecContext(ctx, "DELETE FROM "+table+" WHERE rowid = ?", rowid); err != nil {
			return err
		}
	}
	return nil
}

// InsertFTSParams are the arguments to InsertFTS.
type InsertFTSParams struct {
	Rowid       int64
	Title       string
	Description string
	Ingredients string
	Tags        string
}

// InsertFTS adds the full-text entries keyed by rowid, folded (db.Fold, the
// SQL function fold) the way a search is.
func (q *Queries) InsertFTS(ctx context.Context, arg InsertFTSParams) error {
	for _, table := range ftsTables {
		if _, err := q.db.ExecContext(ctx,
			"INSERT INTO "+table+" (rowid, title, description, ingredients, tags) VALUES (?, fold(?), fold(?), fold(?), fold(?))",
			arg.Rowid, arg.Title, arg.Description, arg.Ingredients, arg.Tags,
		); err != nil {
			return err
		}
	}
	return nil
}
